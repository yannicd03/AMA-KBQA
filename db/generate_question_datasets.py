"""
Generate Standardized Question Datasets

This script generates reproducible JSON questionnaire files for KQAPro and SciQA datasets.
These files can be loaded by batch runners for consistent benchmarking.

Usage:
    python db/generate_question_datasets.py --dataset kqapro --n 100 --seed 42
    python db/generate_question_datasets.py --dataset sciqa --n 50 --seed 42 --sciqa-source handcrafted
    python db/generate_question_datasets.py --dataset both --n 100 --seed 42
"""

from __future__ import annotations
import argparse
import csv
import json
import random
import sys
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, List, Optional

# Path configuration
SCRIPT_DIR = Path(__file__).resolve().parent
PROJECT_ROOT = SCRIPT_DIR.parent

# Dataset paths
KQAPRO_VAL_PATH = SCRIPT_DIR / "datasets" / "kqapro" / "val.json"
SCIQA_HANDCRAFTED_PATH = SCRIPT_DIR / "datasets" / "SciQA" / "Handcrafted" / "full dataset.csv"
SCIQA_AUTOGENERATED_PATH = SCRIPT_DIR / "datasets" / "SciQA" / "Autogenerated" / "full dataset.csv"

# Known dataset sizes
SCIQA_HANDCRAFTED_MAX = 100
SCIQA_AUTOGENERATED_MAX = 2465


def load_kqapro_dataset() -> List[Dict[str, Any]]:
    """Load the KQAPro validation dataset."""
    if not KQAPRO_VAL_PATH.exists():
        raise FileNotFoundError(f"KQAPro dataset not found at {KQAPRO_VAL_PATH}")

    with open(KQAPRO_VAL_PATH, "r", encoding="utf-8") as f:
        data = json.load(f)

    print(f"[OK] Loaded {len(data)} questions from KQAPro validation dataset")
    return data


def load_sciqa_dataset(dataset_type: str = "handcrafted") -> List[Dict[str, Any]]:
    """
    Load the SciQA dataset from CSV file.

    Args:
        dataset_type: Either "handcrafted" or "autogenerated"

    Returns:
        List of questions with metadata
    """
    if dataset_type == "handcrafted":
        csv_path = SCIQA_HANDCRAFTED_PATH
    else:
        csv_path = SCIQA_AUTOGENERATED_PATH

    if not csv_path.exists():
        raise FileNotFoundError(f"SciQA dataset not found at {csv_path}")

    data = []
    with open(csv_path, "r", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            # Handle different column names between handcrafted and autogenerated
            if dataset_type == "handcrafted":
                # Handcrafted format
                question = row.get("Paraphrase", "").strip()
                if not question:
                    question = row.get("Question without context (comparison)", "").strip()
                answer = row.get("Result", "").strip()
                sparql_query = row.get("Machine-readable query", "").strip()
                q_type = row.get("Q Content", row.get("ORKG-based type", "")).strip()
                research_field = row.get("Research field", "").strip()
            else:
                # Autogenerated format has different column names
                question = row.get("Question", "").strip()
                answer = row.get("Answer", "").strip()
                sparql_query = row.get("Query", "").strip()
                q_type = row.get("Q Type", "").strip()
                research_field = ""  # Not available in autogenerated

            if question and answer:
                data.append({
                    "question": question,
                    "answer": answer,
                    "sparql_query": sparql_query,
                    "q_type": q_type,
                    "research_field": research_field,
                    "raw": row  # Preserve all original columns
                })

    print(f"[OK] Loaded {len(data)} questions from SciQA {dataset_type} dataset")
    return data


def sample_questions(data: List[Dict[str, Any]], n: int, seed: int) -> List[Dict[str, Any]]:
    """Randomly sample n questions from the dataset with a fixed seed."""
    random.seed(seed)
    n_sample = min(n, len(data))
    sampled = random.sample(data, n_sample)
    print(f"[OK] Sampled {n_sample} questions with seed={seed}")
    return sampled


def generate_kqapro_questionnaire(
    n: int,
    seed: int,
    output_dir: Path
) -> Path:
    """
    Generate a KQAPro questionnaire JSON file.

    Args:
        n: Number of questions to sample
        seed: Random seed for reproducibility
        output_dir: Directory to save the output file

    Returns:
        Path to the generated file
    """
    print(f"\n{'='*60}")
    print("Generating KQAPro Questionnaire")
    print(f"{'='*60}")

    # Load dataset
    data = load_kqapro_dataset()

    # Sample questions
    sampled = sample_questions(data, n, seed)

    # Format questions with IDs
    questions = []
    for i, item in enumerate(sampled):
        questions.append({
            "id": i,
            "question": item["question"],
            "answer": item["answer"],
            "choices": item.get("choices", []),
            "sparql": item.get("sparql", ""),
            "program": item.get("program", [])
        })

    # Build output structure
    output = {
        "metadata": {
            "dataset": "kqapro",
            "source_file": str(KQAPRO_VAL_PATH.relative_to(PROJECT_ROOT)),
            "total_source_questions": len(data),
            "sample_size": len(sampled),
            "seed": seed,
            "generated_at": datetime.now().isoformat()
        },
        "questions": questions
    }

    # Save to file
    output_path = output_dir / "kqapro_questionnaire.json"
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(output, f, indent=2, ensure_ascii=False)

    print(f"[OK] Saved KQAPro questionnaire to: {output_path}")
    print(f"     - {len(questions)} questions")

    return output_path


def generate_sciqa_questionnaire(
    n: int,
    seed: int,
    source: str,
    output_dir: Path
) -> Path:
    """
    Generate a SciQA questionnaire JSON file.

    Args:
        n: Number of questions to sample
        seed: Random seed for reproducibility
        source: "handcrafted", "autogenerated", or "both"
        output_dir: Directory to save the output file

    Returns:
        Path to the generated file
    """
    print(f"\n{'='*60}")
    print("Generating SciQA Questionnaire")
    print(f"{'='*60}")

    random.seed(seed)

    questions = []
    sources_info = {}
    question_id = 0

    if source in ("handcrafted", "both"):
        # Load handcrafted dataset
        handcrafted_data = load_sciqa_dataset("handcrafted")
        sources_info["handcrafted"] = {
            "path": str(SCIQA_HANDCRAFTED_PATH.relative_to(PROJECT_ROOT)),
            "total_questions": len(handcrafted_data)
        }

        if source == "handcrafted":
            # Only handcrafted - sample from it
            if n > SCIQA_HANDCRAFTED_MAX:
                print(f"[WARNING] Requested {n} questions but handcrafted only has {SCIQA_HANDCRAFTED_MAX}. Using all.")
            sampled = sample_questions(handcrafted_data, n, seed)
            sources_info["handcrafted"]["sampled"] = len(sampled)
        else:
            # Both - include all handcrafted first
            sampled = handcrafted_data.copy()
            sources_info["handcrafted"]["sampled"] = len(sampled)

        for item in sampled:
            questions.append({
                "id": question_id,
                "source": "handcrafted",
                "question": item["question"],
                "answer": item["answer"],
                "sparql_query": item.get("sparql_query", ""),
                "q_type": item.get("q_type", ""),
                "research_field": item.get("research_field", ""),
                "raw": item.get("raw", {})
            })
            question_id += 1

    if source in ("autogenerated", "both"):
        # Load autogenerated dataset
        autogenerated_data = load_sciqa_dataset("autogenerated")
        sources_info["autogenerated"] = {
            "path": str(SCIQA_AUTOGENERATED_PATH.relative_to(PROJECT_ROOT)),
            "total_questions": len(autogenerated_data)
        }

        if source == "autogenerated":
            # Only autogenerated - sample from it
            sampled = sample_questions(autogenerated_data, n, seed)
            sources_info["autogenerated"]["sampled"] = len(sampled)
        else:
            # Both - fill remaining from autogenerated
            remaining = max(0, n - len(questions))
            if remaining > 0:
                sampled = sample_questions(autogenerated_data, remaining, seed)
                sources_info["autogenerated"]["sampled"] = len(sampled)
            else:
                sampled = []
                sources_info["autogenerated"]["sampled"] = 0
                print(f"[INFO] Already have {len(questions)} handcrafted questions, no autogenerated needed")

        for item in sampled:
            questions.append({
                "id": question_id,
                "source": "autogenerated",
                "question": item["question"],
                "answer": item["answer"],
                "sparql_query": item.get("sparql_query", ""),
                "q_type": item.get("q_type", ""),
                "research_field": item.get("research_field", ""),
                "raw": item.get("raw", {})
            })
            question_id += 1

    # Build output structure
    output = {
        "metadata": {
            "dataset": "sciqa",
            "sources": sources_info,
            "sample_size": len(questions),
            "seed": seed,
            "generated_at": datetime.now().isoformat()
        },
        "questions": questions
    }

    # Save to file
    output_path = output_dir / "sciqa_questionnaire.json"
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(output, f, indent=2, ensure_ascii=False)

    print(f"[OK] Saved SciQA questionnaire to: {output_path}")
    print(f"     - {len(questions)} questions")

    return output_path


def main():
    parser = argparse.ArgumentParser(
        description="Generate standardized question datasets for benchmarking",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  python db/generate_question_datasets.py --dataset kqapro --n 100 --seed 42
  python db/generate_question_datasets.py --dataset sciqa --n 50 --seed 42 --sciqa-source handcrafted
  python db/generate_question_datasets.py --dataset both --n 100 --seed 42
        """
    )

    parser.add_argument(
        "--dataset",
        type=str,
        choices=["kqapro", "sciqa", "both"],
        default="both",
        help="Dataset to generate (default: both)"
    )

    parser.add_argument(
        "--n",
        type=int,
        default=100,
        help="Number of samples (default: 100)"
    )

    parser.add_argument(
        "--seed",
        type=int,
        default=42,
        help="Random seed (default: 42)"
    )

    parser.add_argument(
        "--sciqa-source",
        type=str,
        choices=["handcrafted", "autogenerated", "both"],
        default="handcrafted",
        help="SciQA source type (default: handcrafted)"
    )

    parser.add_argument(
        "--output-dir",
        type=str,
        default=None,
        help="Output directory (default: db/)"
    )

    args = parser.parse_args()

    # Determine output directory
    if args.output_dir:
        output_dir = Path(args.output_dir)
    else:
        output_dir = SCRIPT_DIR

    output_dir.mkdir(parents=True, exist_ok=True)

    print(f"\n{'='*60}")
    print("Question Dataset Generator")
    print(f"{'='*60}")
    print(f"  Dataset:      {args.dataset}")
    print(f"  Samples:      {args.n}")
    print(f"  Seed:         {args.seed}")
    print(f"  SciQA Source: {args.sciqa_source}")
    print(f"  Output Dir:   {output_dir}")
    print(f"{'='*60}")

    generated_files = []

    try:
        if args.dataset in ("kqapro", "both"):
            path = generate_kqapro_questionnaire(args.n, args.seed, output_dir)
            generated_files.append(path)

        if args.dataset in ("sciqa", "both"):
            path = generate_sciqa_questionnaire(args.n, args.seed, args.sciqa_source, output_dir)
            generated_files.append(path)

        print(f"\n{'='*60}")
        print("Generation Complete")
        print(f"{'='*60}")
        print("Generated files:")
        for f in generated_files:
            print(f"  - {f}")
        print(f"{'='*60}\n")

    except Exception as e:
        print(f"\n[ERROR] Generation failed: {e}")
        sys.exit(1)


if __name__ == "__main__":
    main()
