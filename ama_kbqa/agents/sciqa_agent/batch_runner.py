    is_correct: bool = Field(
        description="Whether the predicted answer matches the gold answer"
    )

    correctness_reasoning: str = Field(
        description="Explanation of why the answer is correct or incorrect"
    )

    argumentation_quality: str = Field(
        description="Assessment of the agent's reasoning structure"
    )

    argumentation_score: int = Field(
        ge=1, le=5,
        description="Numeric score for argumentation (1-5)"
    )

    suggested_improvement: str = Field(
        description="Suggestion for improvement"
    )


