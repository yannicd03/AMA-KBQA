def main():
    parser = argparse.ArgumentParser(
        description="SciQA Batch Runner",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  python batch_runner.py --n_questions 10 --seed 42 --dataset handcrafted
  python batch_runner.py -n 50 --seed 123 --dataset auto --postprocessing llm_judge
  python batch_runner.py --questionnaire db/sciqa_questionnaire.json
        """
    )

    parser.add_argument(
        "-n", "--n_questions",
        type=int,
        default=10,
        help="Number of questions to process (default: 10)"
    )

    parser.add_argument(
        "--seed",
        type=int,
        default=42,
        help="Random seed for reproducibility (default: 42)"
    )

    parser.add_argument(
        "--dataset", "-d",
        type=str,
        choices=["handcrafted", "auto", "autogenerated"],
        default="handcrafted",
        help="Dataset type (default: handcrafted)"
    )

    parser.add_argument(
        "--postprocessing", "-p",
        type=str,
        choices=["llm_judge", "simple"],
        default="llm_judge",
        help="Postprocessing method (default: llm_judge)"
    )

    parser.add_argument(
        "--questionnaire",
        type=str,
        default=None,
        help="Path to a pre-generated questionnaire JSON file (overrides --dataset and --seed sampling)"
    )
    parser.add_argument(
        "--no-fewshot",
        action="store_true",
        default=False,
        help="Disable few-shot example injection (for ablation study)"
    )

    args = parser.parse_args()

    asyncio.run(run_batch(
        n_questions=args.n_questions,
        seed=args.seed,
        dataset_type=args.dataset,
        postprocessing_mode=args.postprocessing,
        questionnaire_path=args.questionnaire,
        use_fewshot=not args.no_fewshot
    ))


if __name__ == "__main__":
    main()
